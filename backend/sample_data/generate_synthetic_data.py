def generate_sbi_pdf():
    """Account D: State Bank of India PDF Statement with ReportLab tables completing Circular Flow back to HDFC."""
    file_path = os.path.join(OUTPUT_DIR, "statement_sbi_john_doe_synthetic.pdf")
    doc = SimpleDocTemplate(file_path, pagesize=letter)
    styles = getSampleStyleSheet()

    elements = []

    # Title & Metadata
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=16,
        leading=20,
        textColor=colors.HexColor("#1e293b"),
    )
    sub_style = ParagraphStyle(
        "SubTitle",
        parent=styles["Normal"],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748b"),
    )

    elements.append(Paragraph("STATE BANK OF INDIA - ACCOUNT STATEMENT", title_style))
    elements.append(Paragraph("SYNTHETIC TEST DATA FOR COMPLIANCE VERIFICATION ONLY", sub_style))
    elements.append(Spacer(1, 10))

    meta_text = (
        "<b>Account Holder:</b> John Doe<br/>"
        "<b>Account Number:</b> 30221144556<br/>"
        "<b>Bank Name:</b> State Bank of India<br/>"
        "<b>Branch:</b> Commercial Branch Mumbai<br/>"
        "<b>Currency:</b> INR"
    )
    elements.append(Paragraph(meta_text, styles["Normal"]))
    elements.append(Spacer(1, 15))

    # Table of transactions completing Circular Loop:
    # Prime Holdings transfers to SBI, SBI transfers back to HDFC Acc 5010022334455
    table_data = [
        ["Date", "Description", "Ref No", "Debit", "Credit", "Balance"],
        ["2026-02-03", "SYNTHETIC: Transfer from Prime Holdings Corp", "REF40001", "", "88000.00", "88000.00"],
        ["2026-02-04", "SYNTHETIC: Transfer to HDFC Acc 5010022334455", "REF40002", "85000.00", "", "3000.00"],
    ]

    t = Table(table_data, colWidths=[70, 190, 70, 60, 60, 60])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 9),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
        ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#f8fafc")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("FONTSIZE", (0, 1), (-1, -1), 8),
    ]))

    elements.append(t)
    doc.build(elements)
    return file_path


